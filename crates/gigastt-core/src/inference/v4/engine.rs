pub(super) fn inference_error(source: anyhow::Error) -> GigasttError {
    GigasttError::Inference {
        source: source.into_boxed_dyn_error(),
    }
}
pub(super) fn model_error(path: String, source: anyhow::Error) -> GigasttError {
    GigasttError::ModelLoad {
        path,
        source: Some(source.into_boxed_dyn_error()),
    }
}

/// Explicit mono 16 kHz PCM and valid length for a v4 full-context request.
/// Padding is never generated by this type or the engine.
#[derive(Debug, Clone, Copy)]
pub struct V4Pcm<'a> {
    samples: &'a [f32],
    valid_samples: usize,
}
impl<'a> V4Pcm<'a> {
    /// Interpret all supplied samples as valid.
    pub fn full(samples: &'a [f32]) -> Self {
        Self {
            samples,
            valid_samples: samples.len(),
        }
    }
    /// Interpret the supplied physical buffer and an explicitly valid prefix.
    /// Invalid lengths are rejected before any inference.
    pub fn padded(samples: &'a [f32], valid_samples: usize) -> Self {
        Self {
            samples,
            valid_samples,
        }
    }
}

/// Metadata for an emitted nonblank RNNT token.
#[derive(Debug, Clone, PartialEq)]
pub struct V4Token {
    /// Exact SentencePiece ID (RNNT blank is never emitted here).
    pub id: usize,
    /// Zero-based encoder frame on the full-context utterance or absolute streaming grid.
    pub frame: usize,
    /// Selected-label probability `exp(log_softmax)` computed in f64.
    /// Not a calibrated probability of transcript correctness.
    pub confidence: f64,
}

/// An explicit v4 single-style result, retaining author's literal decoded
/// text separately from its author-style word grouping.
#[derive(Debug, Clone)]
pub struct V4Transcription {
    /// Independently selected raw or e2e head.
    pub style: TranscriptStyle,
    /// Exact SentencePiece sequence decode (no extra punctuation/ITN).
    pub text: String,
    /// All emitted nonblank tokens with frames and model probabilities.
    pub tokens: Vec<V4Token>,
    /// Literal author-style word groups on the valid timestamp grid.
    /// Confidence is gigastt's mean selected token confidence per group;
    /// the author's public text API does not expose confidence.
    pub words: Vec<WordInfo>,
    /// Physical/valid sample, mel and encoder geometry, checked at runtime.
    pub grid: V4FrameGrid,
    /// Valid audio duration in seconds.
    pub duration_s: f64,
    /// Duration-weighted word confidence, or None with no lexical groups.
    pub confidence: Option<f32>,
    #[cfg(test)]
    trace: decode::Trace,
    #[cfg(test)]
    word_spans: Vec<std::ops::Range<usize>>,
}

/// Both independent output styles from a single shared acoustic encoder call.
#[derive(Debug, Clone)]
pub struct V4DualTranscription {
    /// Exact unformatted raw output.
    pub raw: V4Transcription,
    /// Exact formatted end-to-end output.
    pub e2e: V4Transcription,
    #[cfg(test)]
    encoded: Vec<f32>,
    #[cfg(test)]
    features: Vec<f32>,
}

struct Head {
    tokenizer: V4Tokenizer,
    predictor: Box<dyn RuntimeSession>,
    joiner: Box<dyn RuntimeSession>,
}
impl Head {
    fn load(pack: &QualifiedV4Pack, style: TranscriptStyle) -> AnyResult<Self> {
        let (predictor, joiner) = match style {
            TranscriptStyle::Raw => (ArtifactRole::RawDecoder, ArtifactRole::RawJoint),
            TranscriptStyle::E2e => (ArtifactRole::E2eDecoder, ArtifactRole::E2eJoint),
        };
        let tokenizer = V4Tokenizer::from_pack(pack, style)?;
        let predictor = load_verified_cpu(pack.read_graph_bytes(predictor)?)?;
        let joiner = load_verified_cpu(pack.read_graph_bytes(joiner)?)?;
        Ok(Self {
            tokenizer,
            predictor,
            joiner,
        })
    }
    fn decode(
        &self,
        encoded: &decode::Encoded,
        grid: V4FrameGrid,
        cancel: Option<&AtomicBool>,
    ) -> Result<V4Transcription, GigasttError> {
        let trajectory = decode::greedy(
            self.predictor.as_ref(),
            self.joiner.as_ref(),
            encoded,
            cancel,
        )?;
        let ids: Vec<usize> = trajectory.tokens.iter().map(|t| t.id).collect();
        let frames: Vec<usize> = trajectory.tokens.iter().map(|t| t.frame).collect();
        let probabilities: Vec<f64> = trajectory.tokens.iter().map(|t| t.confidence).collect();
        let text = self.tokenizer.decode(&ids).map_err(inference_error)?;
        let (words, _word_spans) = self
            .tokenizer
            .word_infos(&ids, &frames, &probabilities, &grid)
            .map_err(inference_error)?;
        let confidence = aggregate_confidence(&words);
        decode::check_cancel(cancel)?;
        Ok(V4Transcription {
            style: self.tokenizer.style(),
            text,
            tokens: trajectory.tokens,
            words,
            grid,
            duration_s: grid.valid_samples() as f64 / 16_000.0,
            confidence,
            #[cfg(test)]
            trace: trajectory.trace,
            #[cfg(test)]
            word_spans: _word_spans,
        })
    }
}

/// Explicit local GigaAM v4 FP32 CPU full-context engine.
///
/// This is separate from the legacy `Engine`. Exactly one acoustic encoder
/// and each style's own predictor/joiner/tokenizer are loaded. One synchronous
/// request owns the engine slot at a time; all predictor state is local to
/// that request. There is no streaming, download, legacy graph cache, or
/// automatic provider/model/precision fallback.
pub struct V4Engine {
    frontend: V4Frontend,
    encoder: Box<dyn RuntimeSession>,
    raw: Head,
    e2e: Head,
    request: Mutex<()>,
    pack_identity: String,
}

impl V4Engine {
    /// Load the exact local versioned pack and explicit qualified MKL runtime.
    pub fn load(pack_dir: &Path, mkl_runtime_dir: &Path) -> Result<Self, GigasttError> {
        let pack = QualifiedV4Pack::load(pack_dir)
            .map_err(|e| model_error(pack_dir.display().to_string(), e))?;
        Self::from_pack(&pack, mkl_runtime_dir)
    }
    /// Build from a validated pack snapshot. The tokenizer and graph bytes are
    /// reverified at their actual parser/session boundary. The encoder bytes
    /// are loaded from memory, not a later unverified path open.
    pub fn from_pack(pack: &QualifiedV4Pack, mkl_runtime_dir: &Path) -> Result<Self, GigasttError> {
        let load = || -> AnyResult<Self> {
            let frontend = V4Frontend::from_pack(pack, mkl_runtime_dir)?;
            let encoder = load_verified_cpu(pack.read_graph_bytes(ArtifactRole::Encoder)?)?;
            let raw = Head::load(pack, TranscriptStyle::Raw)?;
            let e2e = Head::load(pack, TranscriptStyle::E2e)?;
            Ok(Self {
                frontend,
                encoder,
                raw,
                e2e,
                request: Mutex::new(()),
                pack_identity: pack.identity().to_owned(),
            })
        };
        load().map_err(|e| model_error(format!("qualified v4 pack {}", pack.identity()), e))
    }
    /// Identity of all verified pack artifacts, independent of local filenames.
    pub fn pack_identity(&self) -> &str {
        &self.pack_identity
    }

    fn acquire(&self, cancel: Option<&AtomicBool>) -> Result<MutexGuard<'_, ()>, GigasttError> {
        acquire_request_slot(&self.request, cancel)
    }
    fn features(
        &self,
        input: V4Pcm<'_>,
        cancel: Option<&AtomicBool>,
    ) -> Result<super::V4Features, GigasttError> {
        decode::check_cancel(cancel)?;
        validate_pcm(input.samples, input.valid_samples).map_err(|e| {
            GigasttError::InvalidAudio {
                reason: format!("{e:#}"),
            }
        })?;
        let result = self
            .frontend
            .compute_padded(input.samples, input.valid_samples);
        decode::check_cancel(cancel)?;
        result.map_err(inference_error)
    }
    fn encode(
        &self,
        values: Vec<f32>,
        grid: &V4FrameGrid,
        cancel: Option<&AtomicBool>,
    ) -> Result<decode::Encoded, GigasttError> {
        decode::encode_features(self.encoder.as_ref(), values, grid, cancel)
    }
    fn decode_both(
        &self,
        values: Vec<f32>,
        grid: V4FrameGrid,
        cancel: Option<&AtomicBool>,
    ) -> Result<V4DualTranscription, GigasttError> {
        #[cfg(test)]
        let features = values.clone();
        let encoded = self.encode(values, &grid, cancel)?;
        let raw = self.raw.decode(&encoded, grid, cancel)?;
        let e2e = self.e2e.decode(&encoded, grid, cancel)?;
        decode::check_cancel(cancel)?;
        Ok(V4DualTranscription {
            raw,
            e2e,
            #[cfg(test)]
            encoded: encoded.data,
            #[cfg(test)]
            features,
        })
    }
    /// Recognize a single explicitly selected style. Cancellation is
    /// cooperative: it is checked while waiting for the slot and before and
    /// after each native call; in-flight native inference is not preempted.
    /// Cancelled requests return no transcript or partial state.
    pub fn transcribe(
        &self,
        input: V4Pcm<'_>,
        style: TranscriptStyle,
        cancel: Option<&AtomicBool>,
    ) -> Result<V4Transcription, GigasttError> {
        let _slot = self.acquire(cancel)?;
        let features = self.features(input, cancel)?;
        let encoded = self.encode(features.values, &features.grid, cancel)?;
        let head = match style {
            TranscriptStyle::Raw => &self.raw,
            TranscriptStyle::E2e => &self.e2e,
        };
        head.decode(&encoded, features.grid, cancel)
    }
    /// Recognize both styles using a single acoustic encoder run. No partial
    /// raw result is returned if cancellation interrupts the second head.
    pub fn transcribe_both(
        &self,
        input: V4Pcm<'_>,
        cancel: Option<&AtomicBool>,
    ) -> Result<V4DualTranscription, GigasttError> {
        let _slot = self.acquire(cancel)?;
        let features = self.features(input, cancel)?;
        self.decode_both(features.values, features.grid, cancel)
    }
}

pub(super) fn acquire_request_slot<'a>(
    request: &'a Mutex<()>,
    cancel: Option<&AtomicBool>,
) -> Result<MutexGuard<'a, ()>, GigasttError> {
    loop {
        decode::check_cancel(cancel)?;
        if let Some(guard) = request.try_lock_for(Duration::from_millis(10)) {
            decode::check_cancel(cancel)?;
            return Ok(guard);
        }
    }
}

